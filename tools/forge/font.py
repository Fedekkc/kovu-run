def glyphs() -> dict[str, list[str]]:
    table: dict[str, list[str]] = {}
    for char, rows in _BASE.items():
        width = len(rows[0])
        table[char] = [BLANK * width] * ACCENT_ROWS + list(rows)
    for char, (base, mark) in _ACCENTED.items():
        table[char] = list(_MARKS[mark]) + list(_BASE[base])
    table[" "] = [BLANK * SPACE_W] * HEIGHT
    return table


def catalog() -> dict[str, object]:
    return {"height": HEIGHT, "ink": INK, "glyphs": glyphs()}
